def bbox(g):
    xs, ys = [], []
    for y, r in enumerate(g):
        for x, ch in enumerate(r):
            if ch != ".":
                xs.append(x); ys.append(y)
    return (min(xs), min(ys), max(xs), max(ys))

def trim(g):
    x0, y0, x1, y1 = bbox(g)
    return [r[x0:x1 + 1] for r in g[y0:y1 + 1]], x0, y0

out = {}
for name, g in SPRITES.items():
    t, ox, oy = trim(g)
    out[name] = t
    w = len(t[0]); h = len(t)
    assert all(len(r) == w for r in t), (name, [len(r) for r in t])
    print("%-8s %2dx%-3d" % (name, w, h))

# ---- preview sheet ----
SC = 4
PAD = 6
cols = 12
cellw = max(len(max(v, key=len)) for v in out.values()) + PAD
cellh = max(len(v) for v in out.values()) + PAD
sheet = Image.new("RGB", (cols * cellw * SC, ((len(out) + cols - 1) // cols) * cellh * SC), (16, 8, 5))
d = ImageDraw.Draw(sheet)
for i, (name, g) in enumerate(out.items()):
    cx = (i % cols) * cellw * SC
    cy = (i // cols) * cellh * SC
    for y, row in enumerate(g):
        for x, ch in enumerate(row):
            if ch == ".":
                continue
            col = PAL.get(ch, "#ff00ff")
            c = tuple(int(col[1 + 2 * k:3 + 2 * k], 16) for k in range(3))
            d.rectangle([cx + x * SC, cy + y * SC, cx + x * SC + SC - 1, cy + y * SC + SC - 1], fill=c)
    d.text((cx + 2, cy + 2), name, fill=(255, 255, 255))
sheet.save(os.path.join(OUT, "sheet_sprites.png"))
print("saved sheet_sprites.png", sheet.size)

