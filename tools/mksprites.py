def blank():
    return [["." for _ in range(W)] for _ in range(H)]

def put(g, x, y, rows, ox=0, oy=0):
    for j, r in enumerate(rows):
        for i, ch in enumerate(r):
            if ch != ".":
                X, Y = x + ox + i, y + oy + j
                if 0 <= X < W and 0 <= Y < H:
                    g[Y][X] = ch

