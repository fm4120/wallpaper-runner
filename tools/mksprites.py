def build_char(legs, arm, tail_on=True):
    g = blank()
    bx, by = 7, 0
    # tail first (behind the body)
    if tail_on:
        put(g, bx, by, [r"111.", r".111", r"..11", r"...1", r"...."], 9, 4)
    put(g, bx, by, BODY, 11, 7)
    put(g, bx, by, HEAD_W, 15, 0)
    for (x, y, rows) in EYE:
        put(g, bx, by, rows, x, y)
    for (x, y, rows) in TONGUE:
        put(g, bx, by, rows, x - 4, y + 7)
    for (x, y, rows) in arm:
        put(g, bx, by, rows, x, y + 7)
    put(g, bx, by, legs, 11, 15)
    return g

